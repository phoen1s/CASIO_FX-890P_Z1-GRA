void convertir_a_columnas(unsigned char *src, unsigned char *dst)
{
    int w = src[0];
    int h = src[1];
    int bpf = (w + 7) >> 3;
    int bpc = (h + 7) >> 3;
    unsigned char *datos = &src[2];
    int x;
    int y;
    int bit;
    int grupo;
    for (grupo = 0; grupo < bpc; grupo++)
    {
        for (x = 0; x < w; x++)
        {
            unsigned char byte = 0;
            for (bit = 0; bit < 8; bit++)
            {
                y = grupo * 8 + bit;
                if (y < h)
                {
                    int bf = y * bpf + (x >> 3);
                    int bt = 7 - (x & 7);
                    if (datos[bf] & (1 << bt))
                    {
                        byte |= (1 << (7 - bit));
                    }
                }
            }
            dst[grupo * w + x] = byte;
        }
    }
}

